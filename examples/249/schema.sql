-- 실습 249 — 상품 표(products) 만들기 + 보안(RLS) 설정 + 예시 데이터
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이 실습의 보안 포인트:
--   이번엔 '쇼핑몰 상품 목록'을 브라우저로 '읽어(SELECT)' 옵니다.
--   상품 이름·가격·사진은 어차피 손님 누구나 봐야 하는 '공개 정보'이므로,
--   RLS를 켜고 "읽기(SELECT)만 누구에게나 허용" 정책을 답니다.
--   대신 쓰기(INSERT/UPDATE/DELETE) 정책은 일부러 안 만들어, anon(공개) 키로는
--   가격을 함부로 바꾸거나 상품을 지울 수 없게 막아 둡니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 상품 표 만들기
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id          bigint generated always as identity primary key,
  name        text        not null,            -- 상품 이름
  price       integer     not null,            -- 가격 (원 단위 정수, 예: 12900)
  image_url   text,                            -- 상품 사진 주소 (없으면 비워도 됨)
  description text,                             -- 한 줄 설명
  created_at  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.products enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [읽기 정책] 누구나 상품 목록을 SELECT(조회)할 수 있게 허용
-- ---------------------------------------------------------------------
-- 정책을 다시 실행해도 에러 안 나게, 같은 이름이 있으면 먼저 지웁니다.
drop policy if exists "anyone can read products" on public.products;

-- for select          : 이 정책은 '읽기(select)' 동작에만 적용된다.
-- to anon, authenticated : 비로그인 손님(anon) + 로그인 사용자 모두 대상.
-- using (true)        : '보여 줄 줄'을 고르는 조건. true = 모든 상품 줄을 보여준다.
--                       (select/delete 에서는 with check 대신 using 을 씁니다.)
create policy "anyone can read products"
  on public.products
  for select
  to anon, authenticated
  using (true);


-- =====================================================================
-- (중요) 쓰기(INSERT/UPDATE/DELETE) 정책은 일부러 만들지 않았습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → anon(공개) 키로는 상품을 '추가/수정/삭제할 수 없습니다'.
--   → 손님은 목록을 '구경만' 할 수 있고, 가격을 조작하거나 상품을 지울 수 없는
--     안전한 상태가 됩니다.
--
--   상품은 누가 추가/수정하나요?
--     - 운영자(나)는 Supabase 대시보드 > Table editor 에서 직접 넣고 고칩니다.
--       (대시보드는 service_role 권한 → RLS와 무관하게 다 됩니다.)
--     - 코드로 상품을 등록/수정해야 한다면, 그건 브라우저가 아니라
--       '서버(예: n8n, 백엔드)'에서 service_role 키로 해야 합니다.
-- =====================================================================


