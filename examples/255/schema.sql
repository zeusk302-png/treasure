-- =====================================================================
-- 실습 255 — 예약 표(reservations) 만들기 + 중복 방지 + 보안(RLS) 설정
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이번 실습이 하는 일:
--   손님이 '날짜 + 시간대'를 골라 예약을 저장(INSERT)합니다.
--   같은 날짜·같은 시간대는 한 번만 예약되게(중복 방지) 막고,
--   이미 예약된 시간대는 화면(드롭다운)에서 '예약 마감'으로 비활성화합니다.
--   즉 "DB를 조회한 결과로 UI(버튼/선택지)를 켜고 끄는" 조건부 UI 패턴입니다.
--
-- 중복 방지의 핵심:
--   (slot_date, slot_time) 두 칸을 묶어 UNIQUE(유일) 제약을 겁니다.
--   → 같은 날짜+시간대 조합은 표에 '딱 한 줄'만 들어갈 수 있습니다.
--   → 두 사람이 동시에 같은 시간을 눌러도, 한 명만 성공하고
--     나머지는 DB가 거절(에러)합니다. (= 화면 검사만으로는 못 막는 동시성까지 차단)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 예약 표 만들기
-- ---------------------------------------------------------------------
create table if not exists public.reservations (
  id          bigint generated always as identity primary key,
  name        text        not null,            -- 예약자 이름
  slot_date   date        not null,            -- 예약 날짜 (예: 2026-06-20)
  slot_time   text        not null,            -- 예약 시간대 (예: '10:00')
  created_at  timestamptz not null default now(),

  -- ★ 중복 방지의 핵심 ★
  -- 날짜 + 시간대 조합을 '유일(unique)'하게 묶습니다.
  -- 같은 날짜에 같은 시간대를 두 번 저장하려 하면 DB가 거절합니다.
  constraint reservations_slot_unique unique (slot_date, slot_time)
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.reservations enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [읽기 정책] 어떤 시간대가 찼는지 누구나 SELECT 할 수 있게 허용
-- ---------------------------------------------------------------------
-- 화면에서 '이미 찬 시간대'를 회색으로 막으려면, 누가 예약했는지까지는 몰라도
-- "그 시간대가 찼다"는 사실은 읽을 수 있어야 합니다.
drop policy if exists "anyone can read reservations" on public.reservations;

-- for select          : 이 정책은 '읽기(select)' 동작에만 적용된다.
-- to anon, authenticated : 비로그인 손님(anon) + 로그인 사용자 모두 대상.
-- using (true)        : 모든 예약 줄을 읽을 수 있다(어느 시간대가 찼는지 확인용).
create policy "anyone can read reservations"
  on public.reservations
  for select
  to anon, authenticated
  using (true);


-- ---------------------------------------------------------------------
-- 4단계) [쓰기 정책] 누구나 예약을 INSERT(저장) 할 수 있게 허용
-- ---------------------------------------------------------------------
-- 이번 실습은 '로그인 없는 간단 예약'이라, 손님 누구나 예약을 넣을 수 있게 합니다.
-- (수정/삭제 정책은 일부러 안 만들어, anon 키로는 남의 예약을 못 고치고 못 지웁니다.)
drop policy if exists "anyone can create reservation" on public.reservations;

-- for insert          : '저장(insert)' 동작에만 적용.
-- with check (true)   : 들어오는 모든 새 줄을 허용한다.
--   ※ 단, 위 UNIQUE 제약(중복 방지)은 RLS와 별개로 항상 동작합니다.
--     즉 정책이 허락해도, 같은 날짜+시간대면 제약이 거절합니다.
create policy "anyone can create reservation"
  on public.reservations
  for insert
  to anon, authenticated
  with check (true);


-- =====================================================================
-- (중요) 수정(UPDATE)·삭제(DELETE) 정책은 일부러 만들지 않았습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → anon(공개) 키로는 예약을 '고치거나 지울 수 없습니다'.
--   → 손님은 예약을 '새로 넣고, 찬 시간대를 구경'만 할 수 있습니다.
--
--   예약 취소/관리는 누가 하나요?
--     - 운영자(나)는 Supabase 대시보드 > Table editor 에서 직접 지우거나 고칩니다.
--       (대시보드는 service_role 권한 → RLS와 무관하게 다 됩니다.)
--     - 코드로 취소 기능을 만들려면, 그건 브라우저가 아니라
--       '서버(예: n8n, 백엔드)'에서 service_role 키로 해야 합니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 5단계) (선택) 동작 확인용 — 미리 한 칸을 '찬 시간대'로 만들어 두기
-- ---------------------------------------------------------------------
-- 아래 한 줄을 실행하면, 2026-06-20 의 '10:00' 이 미리 예약된 상태가 됩니다.
-- 그러면 화면 드롭다운에서 그 시간대가 '예약 마감'으로 회색 처리되는 걸
-- 바로 눈으로 확인할 수 있습니다. (원치 않으면 이 줄은 건너뛰어도 됩니다.)
insert into public.reservations (name, slot_date, slot_time)
values ('샘플 예약자', '2026-06-20', '10:00')
on conflict (slot_date, slot_time) do nothing;  -- 이미 있으면 조용히 넘어감


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--
--   - anon key (공개 키, sb_publishable_...) : 화면(브라우저)·script.js·깃허브에
--     올려도 되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전.
--     이번 실습에선 'SELECT + INSERT'만 허락했으므로, 예약 등록/마감 확인은 되고
--     남의 예약 수정·삭제는 막힙니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     정책이 뭐든 무시하고 다 됩니다. 그래서 절대! 브라우저·코드·깃허브에 올리면 안 되고
--     오직 서버(예: n8n, 백엔드)에서만 비밀로 보관해 씁니다.
-- =====================================================================
