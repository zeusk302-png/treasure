-- =====================================================================
-- 실습 264 — 주문 표(orders) 만들기 + 통계용 읽기 정책(RLS) 설정
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이번 실습이 하는 일:
--   가게의 '주문(orders)' 데이터를 모아 두고,
--   대시보드에서 그 데이터를 '집계(합치기/세기/평균내기)'해
--   핵심 지표(KPI) 카드 4개로 한눈에 보여 줍니다.
--     · 주문 건수 (몇 건이나 들어왔나)        → COUNT
--     · 매출 합계 (다 더하면 얼마인가)         → SUM
--     · 평균 주문액 (한 건당 평균 얼마인가)     → AVG
--     · 고객 수 (서로 다른 손님은 몇 명인가)    → DISTINCT COUNT
--
--   "표에 쌓인 낱개 데이터를 한 줄 요약 숫자로 바꾸는 것" = 집계(aggregate)입니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 주문 표 만들기
-- ---------------------------------------------------------------------
create table if not exists public.orders (
  id          bigint generated always as identity primary key,
  customer    text        not null,            -- 주문한 손님 이름
  amount      integer     not null,            -- 주문 금액(원). 예: 15000
  created_at  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.orders enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [읽기 정책] 통계를 내려면 주문을 SELECT(읽기) 할 수 있어야 함
-- ---------------------------------------------------------------------
-- 대시보드는 주문을 '읽어서' 건수·합계·평균을 계산합니다.
-- 그래서 읽기(select)만 누구에게나 허용합니다.
drop policy if exists "anyone can read orders" on public.orders;

-- for select          : 이 정책은 '읽기(select)' 동작에만 적용된다.
-- to anon, authenticated : 비로그인 손님(anon) + 로그인 사용자 모두 대상.
-- using (true)        : 모든 주문 줄을 읽을 수 있다(집계 계산용).
create policy "anyone can read orders"
  on public.orders
  for select
  to anon, authenticated
  using (true);


-- =====================================================================
-- (중요) 저장(INSERT)·수정(UPDATE)·삭제(DELETE) 정책은 일부러 안 만들었습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → 이 대시보드의 anon(공개) 키로는 주문을 '읽어서 통계만' 낼 수 있고
--     주문을 새로 넣거나 고치거나 지울 수는 없습니다. (= 읽기 전용 화면)
--
--   주문은 누가 넣나요?
--     - 실제 서비스라면 결제/주문 단계에서 '서버(예: n8n, 백엔드)'가
--       service_role 키로 안전하게 INSERT 합니다.
--     - 이번 연습에서는 아래 5단계 샘플 데이터로 채워 두고 통계만 봅니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 4단계) (선택) DB가 직접 통계를 내주는 함수 — 더 빠르고 정확한 방법
-- ---------------------------------------------------------------------
-- 브라우저가 모든 주문을 받아와 더하는 대신,
-- DB에게 "통계만 한 줄로 계산해서 줘"라고 시키는 방법입니다.
-- (주문이 아주 많아질 때 유리합니다. script.js에 두 방법이 다 들어 있습니다.)
create or replace function public.order_stats()
returns table (
  order_count    bigint,
  total_amount   bigint,
  avg_amount     numeric,
  customer_count bigint
)
language sql
stable
security invoker          -- 호출자(anon)의 권한으로 실행 → RLS 정책을 그대로 따름
as $$
  select
    count(*)                         as order_count,    -- 주문 건수
    coalesce(sum(amount), 0)         as total_amount,   -- 매출 합계(없으면 0)
    coalesce(round(avg(amount)), 0)  as avg_amount,     -- 평균 주문액(반올림)
    count(distinct customer)         as customer_count  -- 서로 다른 손님 수
  from public.orders;
$$;


-- ---------------------------------------------------------------------
-- 5단계) (선택) 동작 확인용 — 샘플 주문 6건 넣기
-- ---------------------------------------------------------------------
-- 표가 비어 있으면 모든 카드가 0으로 보이니, 통계가 잘 나오는지 확인하려고
-- 샘플을 미리 넣어 둡니다. (이미 데이터가 있으면 이 단계는 건너뛰어도 됩니다.)
insert into public.orders (customer, amount) values
  ('홍길동', 15000),
  ('김영희', 8000),
  ('홍길동', 23000),   -- 홍길동의 두 번째 주문(고객 수는 그대로 세는지 확인용)
  ('이철수', 42000),
  ('박지민', 5000),
  ('김영희', 19000);


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--
--   - anon key (공개 키, sb_publishable_...) : 화면(브라우저)·script.js·깃허브에
--     올려도 되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전.
--     이번 실습에선 'SELECT(읽기)'만 허락했으므로, 통계는 볼 수 있지만
--     주문 데이터를 넣거나 고치거나 지울 수는 없습니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     정책이 뭐든 무시하고 다 됩니다. 그래서 절대! 브라우저·코드·깃허브에 올리면 안 되고
--     오직 서버(예: n8n, 백엔드)에서만 비밀로 보관해 씁니다.
-- =====================================================================
