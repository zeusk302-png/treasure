// 실습 285 — ==/=== 비교와 타입 강제변환의 함정
// ---------------------------------------------------------------------------
// 이 파일은 "왜 == 가 위험한지"와 "=== 와 타입 변환으로 어떻게 고치는지"를
// 표로 직접 찍어볼 수 있는 작은 데모입니다.
//
// 실행법 1) 터미널에서:   node compare.js
// 실행법 2) 브라우저에서:  F12 콘솔에 이 파일 내용을 붙여 넣고 Enter
// ---------------------------------------------------------------------------

// ── 깨진 입력값 예시 (화면/입력칸/API 에서 흔히 들어오는 값들) ──
// 화면의 글자나 input 값은 "숫자"가 아니라 "문자열"로 들어온다는 점이 핵심입니다.
const 깨진입력값들 = [
  0,      // 진짜 숫자 0 (정상)
  "0",    // 글자 "0"  ← 화면/폼에서 0개일 때 들어오는 값
  "",     // 빈 글자   ← 데이터가 비었을 때
  "  0 ", // 앞뒤 공백 섞인 "0"
  3,      // 진짜 숫자 3
  "3",    // 글자 "3"
  null,   // 값이 아예 없음
];

// ── (나쁜 예) 느슨한 비교 == 로 "비어 있는지" 판단 ──
// "" == 0 → true, "0" 은 if 에서 참 → 0개인데 "담겨 있음"으로 새는 함정.
function 비어있나_나쁨(value) {
  if (value == "") return "비었음(==)"; // null, "", 0 까지 섞여서 true 가 됨
  if (value) return "담겨있음";          // 글자 "0" 도 여기로 새어 들어감
  return "알수없음";
}

// ── (좋은 예) 빈 값 먼저 ===, 그다음 숫자로 변환해서 === ──
function 비어있나_좋음(value) {
  // 1) 진짜 "빈 값"인지 엄격하게 먼저 거른다 (타입까지 같아야 true)
  if (value === null || value === undefined) return "값없음";
  const raw = String(value).trim();
  if (raw === "") return "값없음";

  // 2) 다룰 타입(숫자)으로 명시적으로 변환한 뒤 === 로 비교
  const count = Number(raw);
  if (Number.isNaN(count)) return "숫자아님";
  if (count === 0) return "비었음"; // 0 === 0 만 true → "0" 도 여기서 올바르게 잡힘
  return "담겨있음(" + count + ")";
}

// ── 결과 표로 비교 ──
console.log("입력값\t\t나쁨(==)\t\t좋음(===+변환)");
console.log("------------------------------------------------------------");
for (const v of 깨진입력값들) {
  const label = JSON.stringify(v).padEnd(8, " ");
  console.log(`${label}\t${비어있나_나쁨(v).padEnd(12, " ")}\t${비어있나_좋음(v)}`);
}

// 참고로 동등 비교의 함정을 직접 확인:
console.log("\n[== 의 함정 직접 보기]");
console.log('"" == 0   →', "" == 0);    // true  (둘 다 0으로 강제변환)  ← 위험
console.log('"" === 0  →', "" === 0);   // false (타입이 달라 안전)
console.log('"0" == 0  →', "0" == 0);   // true  ("0" 이 0 으로 변환됨)
console.log('"0" === 0 →', "0" === 0);  // false (글자와 숫자는 다름)
console.log('Boolean("0") →', Boolean("0")); // true ← "0" 은 빈 글자가 아니라서 '참'!
