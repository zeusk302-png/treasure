// 실습 293 — 부동소수점 오차 잡기 (돈 계산에서 float 피하기)
// ---------------------------------------------------------------------------
// 이 파일은 "왜 소수로 돈을 더하면 합계가 틀어지는지"와
// "정수(가장 작은 단위)로 바꾸면 어떻게 정확해지는지"를 표로 직접 찍어보는 데모입니다.
//
// 실행법 1) 터미널에서:   node compare.js
// 실행법 2) 브라우저에서:  F12 콘솔에 이 파일 내용을 붙여 넣고 Enter
// ---------------------------------------------------------------------------

// ── 오차가 났던 입력 조합 예시 ──
// 소수점(원 미만)이 섞인 가격들입니다. 합쳐서 19,999.99원이 "나와야" 정상입니다.
const 장바구니 = [
  { name: "원두 (소분)", price: 6666.66, priceJeon: 666666, qty: 1 },
  { name: "드립백 세트", price: 6666.66, priceJeon: 666666, qty: 1 },
  { name: "텀블러",      price: 6666.67, priceJeon: 666667, qty: 1 },
];

// ── (나쁜 예) 소수(float)끼리 그대로 더하기 ──
// 0.1 + 0.2 가 0.30000000000000004 가 되는 것과 같은 이유로 오차가 쌓입니다.
function 합계_나쁨(items) {
  let 합 = 0;
  for (const it of items) {
    합 = 합 + it.price * it.qty; // 소수 곱셈/덧셈에서 오차 누적
  }
  return 합;
}

// ── (좋은 예) 정수 '전'(=1/100원) 단위로 더하고, 마지막에만 원으로 환산 ──
// 정수끼리의 덧셈은 오차가 전혀 없습니다.
function 합계_좋음_전(items) {
  let 합전 = 0;
  for (const it of items) {
    합전 = 합전 + it.priceJeon * it.qty; // 정수 곱셈/덧셈 → 오차 없음
  }
  return 합전; // 정수(전)
}

function 전을원문자열로(jeon) {
  const 원 = Math.floor(jeon / 100);
  const 소수 = String(jeon % 100).padStart(2, "0");
  return 원.toLocaleString("ko-KR") + "." + 소수 + "원";
}

// ── 결과 비교 ──
const 나쁜합 = 합계_나쁨(장바구니);
const 좋은합전 = 합계_좋음_전(장바구니);

console.log("입력 가격(원):", 장바구니.map((it) => it.price).join(" + "));
console.log("------------------------------------------------------------");
console.log("나쁨(소수로 더함):   ", 나쁜합);                 // 19999.990000000002 류
console.log("나쁨 === 19999.99 ?  ", 나쁜합 === 19999.99);    // false (오차 때문)
console.log("좋음(정수 전 단위):  ", 좋은합전, "전 →", 전을원문자열로(좋은합전)); // 1999999 → "19,999.99원"
console.log("좋음 === 1999999 ?   ", 좋은합전 === 1999999);   // true (정확!)

// ── 부동소수점 함정 직접 보기 ──
console.log("\n[부동소수점 함정 직접 보기]");
console.log("0.1 + 0.2        =", 0.1 + 0.2);             // 0.30000000000000004
console.log("0.1 + 0.2 === 0.3?", 0.1 + 0.2 === 0.3);     // false ← 함정의 본질
console.log("(0.1 + 0.2).toFixed(2) =", (0.1 + 0.2).toFixed(2)); // "0.30" (보기엔 멀쩡)

// ── 차선책: toFixed/반올림으로 "표시"만 다듬기 ──
// 표시(보여주기)만 고치고 싶을 때 쓰지만, 계산을 여러 번 누적하면 또 오차가 생길 수 있어
// "계산은 정수로, 반올림은 마지막 한 번만" 이 가장 안전합니다.
console.log("\n[차선책: 마지막에 반올림만]");
console.log("Math.round(나쁜합 * 100) / 100 =", Math.round(나쁜합 * 100) / 100); // 19999.99
