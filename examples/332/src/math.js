// 왜 있는가:
//   CI가 "테스트가 통과하는지"를 확인하려면 테스트할 함수가 있어야 합니다.
//   일부러 단순하게 만들어, 초보가 "코드 한 줄을 일부러 깨뜨리면 CI가 빨간불을
//   띄운다"는 걸 직접 체험하기 좋게 했습니다.
// ──────────────────────────────────────────────────────────────

// add: 두 숫자를 더해 돌려줍니다. export 를 붙여 다른 파일(테스트)에서 가져다 쓸 수 있게 합니다.
export function add(a, b) {
  return a + b;
}

// slugify: 글 제목 같은 문자열을 URL 주소에 쓸 수 있는 형태('my-post')로 바꿉니다.
// 왜 이런 함수를 예로 두었나: 웹에서 정말 자주 쓰는 작은 유틸이라,
// "이런 함수일수록 자동 테스트로 지켜야 한다"는 감을 주기 위해서입니다.
export function slugify(text) {
  return String(text)
    .trim() // 앞뒤 공백 제거 — 안 하면 "-hello" 처럼 앞에 하이픈이 붙는 실수가 생김
    .toLowerCase() // 주소는 소문자로 통일하는 게 관례라 소문자로
    .replace(/[^a-z0-9가-힣\s-]/g, "") // 영문/숫자/한글/공백/하이픈만 남기고 특수문자 제거
    .replace(/\s+/g, "-") // 띄어쓰기는 하이픈으로 — URL엔 공백을 못 쓰기 때문
    .replace(/-+/g, "-"); // 연속된 하이픈은 하나로 정리해 깔끔하게
}
