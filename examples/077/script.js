// ============================================================
// 스크롤하면 맨 위로 가기 버튼 나타나기
//
// 핵심 아이디어 2가지
//   1) "스크롤 감지": scroll 이벤트로 지금 얼마나 내려왔는지(window.scrollY)
//      를 확인하고, 일정 높이를 넘으면 버튼을 보이게 한다.
//   2) "부드러운 이동": 버튼을 누르면 scrollTo 로 맨 위(0)로 올라가되,
//      behavior: "smooth" 로 뚝 끊기지 않고 미끄러지게 한다.
// ============================================================

// 1) 화면 요소 가져오기 ----------------------------------------
const topBtn = document.getElementById("topBtn"); // 맨 위로 가기 버튼

// 2) 버튼을 보여줄 기준 높이 -----------------------------------
//    화면을 이 픽셀(px)보다 많이 내리면 버튼을 나타냅니다.
//    값을 키우면 더 많이 내려야 버튼이 나오고, 줄이면 금방 나옵니다.
const SHOW_AFTER = 300;

// 3) 스크롤할 때마다 실행되는 함수 -----------------------------
//    window.scrollY 는 '지금 위에서 몇 px 내려왔는가'를 나타내는 숫자입니다.
//    (맨 위는 0, 아래로 내려갈수록 커집니다.)
function handleScroll() {
  if (window.scrollY > SHOW_AFTER) {
    // 기준보다 많이 내려왔으면: 버튼에 show 클래스를 붙여 나타냄
    topBtn.classList.add("show");
  } else {
    // 다시 위로 올라와 기준 아래가 되면: show 를 떼서 숨김
    topBtn.classList.remove("show");
  }
}

// 4) 스크롤 이벤트 연결 ----------------------------------------
//    페이지를 스크롤할 때마다 handleScroll 이 호출됩니다.
window.addEventListener("scroll", handleScroll);

// 5) 버튼 클릭 → 맨 위로 부드럽게 이동 -------------------------
//    top: 0 은 '맨 위(0px)로 가라', behavior: "smooth" 는 '부드럽게' 라는 뜻입니다.
topBtn.addEventListener("click", () => {
  window.scrollTo({ top: 0, behavior: "smooth" });
});

// 6) 첫 실행 ---------------------------------------------------
//    페이지를 새로고침했을 때 이미 아래쪽에 있을 수도 있으므로,
//    처음에 한 번 검사해서 버튼 상태를 맞춰 둡니다.
handleScroll();
