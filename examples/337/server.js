/*
  이 파일은 무엇인가:
  "캐시(Cache-Control) 헤더 적용 데모"를 직접 눈으로 보기 위한 아주 작은 Express 서버입니다.
  같은 정적 파일(이미지·CSS·JS)이라도 어떤 Cache-Control 헤더를 붙이느냐에 따라
  재방문 시 "다시 받느냐 / 디스크에서 즉시 꺼내 쓰느냐"가 달라집니다. 그 차이를 보여 줍니다.

  왜 있는가:
  CDN/배포 플랫폼(Vercel·Netlify·Cloudflare 등)은 결국 이런 "응답 헤더"를 보고 캐시합니다.
  비전공 디렉터가 "왜 내 사이트가 두 번째부터 빠른가 / 왜 파일을 고쳤는데 옛날 게 보이는가"를
  이해하려면, 헤더가 캐시를 어떻게 조종하는지 한 번 직접 만들어 보는 게 가장 빠릅니다.

  실행: node server.js  →  http://localhost:3000 접속 → F12 > Network 탭에서 헤더/캐시 상태 관찰
*/

const express = require("express"); // 가벼운 웹 서버 프레임워크. 정적 파일 서빙과 헤더 제어가 쉬워서 선택.
const path = require("path");

const app = express();
const PORT = process.env.PORT || 3000; // 포트는 환경변수로 바꿀 수 있게 둠(비밀값 아님, 그냥 설정값).

// ─────────────────────────────────────────────────────────────
// 1) HTML 문서: "절대 오래 캐시하면 안 되는" 자원
//    HTML은 페이지의 '지도'라서, 새 배포 후 즉시 최신이 보여야 합니다.
//    그래서 캐시를 막거나(no-store) 매번 서버에 확인하게(no-cache) 합니다.
// ─────────────────────────────────────────────────────────────
app.get("/", (req, res) => {
  // no-store: 브라우저/CDN이 이 응답을 저장조차 하지 말라는 뜻.
  // 왜: index.html이 어떤 버전의 CSS/JS를 부를지 결정하므로, 항상 최신이어야 캐시 무효화가 동작함.
  res.setHeader("Cache-Control", "no-store");
  res.sendFile(path.join(__dirname, "public", "index.html"));
});

// ─────────────────────────────────────────────────────────────
// 2) "해시/버전이 파일명에 박힌" 정적 자원: 아주 길게 + immutable 로 캐시
//    예) /static/app.3f9c1a.js  처럼 파일명 자체가 버전을 품고 있으면,
//    내용이 바뀌면 파일명이 바뀌므로 같은 URL의 내용은 절대 안 변합니다.
//    그래서 1년(31536000초) 동안 재검증 없이 그대로 써도 안전 → 재방문이 즉시 뜸.
// ─────────────────────────────────────────────────────────────
app.use(
  "/static",
  express.static(path.join(__dirname, "public", "static"), {
    setHeaders: (res) => {
      // max-age=31536000(1년) + immutable: "1년간 이 파일은 절대 안 바뀌니 다시 묻지도 마".
      // public: 브라우저뿐 아니라 CDN 같은 공용 캐시도 저장해도 된다는 뜻.
      // 왜 안전한가: 파일명에 버전(해시)이 있어, 내용이 바뀌면 URL이 바뀌기 때문(=캐시 버스팅).
      res.setHeader("Cache-Control", "public, max-age=31536000, immutable");
    },
  })
);

// ─────────────────────────────────────────────────────────────
// 3) "파일명은 그대로인데 가끔 바뀌는" 자원: 짧게 캐시 + 재검증
//    예) 로고처럼 URL은 고정이고 어쩌다 교체되는 이미지.
//    no-cache 는 "저장은 하되, 쓰기 전에 서버에 '안 바뀌었지?'를 꼭 물어봐"라는 뜻.
//    안 바뀌었으면 서버가 304(Not Modified)를 주고, 브라우저는 캐시본을 그대로 써서 빠릅니다.
// ─────────────────────────────────────────────────────────────
app.use(
  "/assets",
  express.static(path.join(__dirname, "public", "assets"), {
    etag: true, // ETag(내용 지문)를 켜야 304 재검증이 동작함.
    setHeaders: (res) => {
      // no-cache: "캐시는 하되 매번 신선도 확인". max-age=0 과 함께 써서 항상 재검증하게 함.
      // 왜: 파일명이 고정이라 캐시 버스팅을 못 쓰므로, 대신 "물어보고 쓰는" 방식으로 최신성을 지킴.
      res.setHeader("Cache-Control", "no-cache, max-age=0, must-revalidate");
    },
  })
);

// ─────────────────────────────────────────────────────────────
// 4) (학습용) 헤더를 한눈에 보는 진단 엔드포인트
//    /headers 로 들어오면, 위 세 종류 자원에 어떤 캐시 정책을 쓰는지 JSON으로 설명해 줍니다.
//    실제 서비스엔 필요 없지만, 비전공자가 "지금 무슨 정책이 걸렸나"를 글로 확인하기 좋게 넣음.
// ─────────────────────────────────────────────────────────────
app.get("/headers", (req, res) => {
  res.setHeader("Cache-Control", "no-store"); // 진단 응답 자체는 캐시하면 안 됨.
  res.json({
    설명: "이 데모가 자원 종류별로 적용하는 Cache-Control 정책 요약",
    정책: {
      "HTML 문서(/)": "no-store — 항상 최신(어떤 버전 파일을 부를지 결정하므로)",
      "버전 박힌 정적자원(/static/*)": "public, max-age=31536000, immutable — 1년 캐시, 재검증 없음",
      "고정 이름 자원(/assets/*)": "no-cache, must-revalidate — 매번 304로 신선도 확인",
    },
  });
});

app.listen(PORT, () => {
  // 콘솔 안내: 어디로 들어가서 무엇을 봐야 하는지 친절히 알려 줌.
  console.log(`캐시 데모 서버 실행 중 → http://localhost:${PORT}`);
  console.log("F12 > Network 탭을 열고 새로고침하며 각 파일의 'Status'와 'Cache-Control'을 보세요.");
});
