-- 이 파일은 무엇인가:
--   Supabase Storage 의 'images' 버킷에 대한 권한(RLS 정책) 예시 모음입니다.
-- 왜 있는가:
--   버킷을 공개(public)로 두면 학습은 쉽지만, 실제 서비스에서는 "누가 올리고
--   누가 볼 수 있는지"를 정책으로 통제해야 합니다. 이 파일은 비공개(private)
--   버킷에 흔히 거는 정책 4가지를 보여 줍니다.
-- 어떻게 쓰나:
--   Supabase 대시보드 > SQL Editor 에 필요한 블록만 붙여넣어 실행합니다.
--
-- 핵심 개념:
--   - Storage 의 파일 목록은 'storage.objects' 라는 테이블처럼 다뤄집니다.
--   - 그 테이블에 RLS(행 수준 보안) 정책을 걸어 INSERT(업로드)/SELECT(조회)/
--     UPDATE/DELETE 권한을 사람·상황별로 허용합니다.
--   - anon(비로그인) vs authenticated(로그인) 역할을 구분해 권한을 줍니다.
--   - service_role 키는 이 모든 정책을 무시하므로 서버에서만 쓰고 절대 노출 금지.
-- ============================================================================


-- 0) (참고) Supabase 에서는 storage.objects 에 RLS 가 이미 켜져 있습니다.
--    혹시 꺼져 있다면 아래로 켭니다. (보통은 그대로 두면 됩니다.)
-- alter table storage.objects enable row level security;


-- ----------------------------------------------------------------------------
-- 1) 누구나(비로그인 포함) 'images' 버킷의 파일을 "볼 수만" 있게 (공개 갤러리용)
--    왜: 프로필 사진처럼 공개해도 되는 이미지를 URL 로 누구나 보게 하려는 경우.
--    주의: 이건 "조회 허용"일 뿐, 업로드는 아래 정책으로 따로 통제합니다.
-- ----------------------------------------------------------------------------
create policy "public read images"
on storage.objects
for select
to anon, authenticated
using ( bucket_id = 'images' );


-- ----------------------------------------------------------------------------
-- 2) 로그인한 사용자만 'images' 버킷에 업로드(INSERT) 가능
--    왜: 아무나 올리면 스토리지가 스팸·악성 파일로 채워질 수 있어, 로그인 사용자로 제한.
-- ----------------------------------------------------------------------------
create policy "authenticated can upload images"
on storage.objects
for insert
to authenticated
with check ( bucket_id = 'images' );


-- ----------------------------------------------------------------------------
-- 3) 자기가 올린 파일만 지울 수 있게 (남의 파일 삭제 방지)
--    왜: owner(파일을 올린 사용자 id)와 현재 로그인 사용자가 같을 때만 삭제 허용.
--    auth.uid() = 현재 로그인한 사용자의 고유 id.
-- ----------------------------------------------------------------------------
create policy "users can delete own images"
on storage.objects
for delete
to authenticated
using ( bucket_id = 'images' and owner = auth.uid() );


