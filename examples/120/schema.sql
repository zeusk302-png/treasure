-- =====================================================================
-- 실습 120 — 할 일(todos) 표 만들고 RLS + 정책 설정하기
-- =====================================================================
-- 지금까지(110~112) 할 일 앱은 localStorage(브라우저)에만 저장됐습니다.
-- 이번에는 그 데이터를 'Supabase 서버의 todos 표'로 옮깁니다(마이그레이션).
--
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--   (1~3단계가 한 번에 실행됩니다. 여러 번 실행해도 안전하게 만들어 뒀습니다.)
-- =====================================================================


-- =====================================================================
-- 1단계) todos 표 만들기
-- =====================================================================
-- localStorage에서 쓰던 객체 한 개:
--     { id: 1718000000000, text: "우유 사기", done: false }
-- 를 표의 '컬럼(열)'로 그대로 옮긴 것이라고 생각하면 됩니다.
--
--   id          : 줄(row)을 구별하는 고유 번호. 서버가 1, 2, 3... 자동으로 매깁니다.
--                 (localStorage 때처럼 Date.now()로 직접 만들 필요가 없습니다.)
--   text        : 할 일 내용 (비어 있으면 안 되므로 not null)
--   done        : 완료 여부. 기본값 false(아직 안 함). 이번 실습에서는 false로만 넣습니다.
--   created_at  : 만든 시각. 서버가 자동으로 '지금 시각'을 넣습니다(now()).
create table if not exists public.todos (
  id          bigint generated always as identity primary key,
  text        text        not null,
  done        boolean     not null default false,
  created_at  timestamptz not null default now()
);


-- =====================================================================
-- 2단계) RLS(행 수준 보안) 켜기
-- =====================================================================
-- RLS = Row Level Security. "표의 줄 하나하나마다 출입 통제를 건다"는 뜻입니다.
-- 이걸 켜면 '정책(policy)으로 허락한 동작'만 가능해집니다(기본은 전부 거절).
-- 정책을 안 만들면 읽기(select)는 빈 배열 [], 쓰기(insert)는 에러로 막힙니다.
alter table public.todos enable row level security;


-- =====================================================================
-- 3단계) 읽기/쓰기 정책 추가하기
-- =====================================================================
-- 이번 실습은 'localStorage → 서버 옮기기'에 집중하므로,
-- 119에서 배운 대로 '누구나 읽기/쓰기 허용' 정책을 답니다.
-- (이렇게 해야 anon 공개 키만으로 select / insert 가 동작합니다.)

-- (읽기 정책) 누구나 할 일 목록을 볼 수 있게 허용 ------------------------
drop policy if exists "anyone can read todos" on public.todos;
create policy "anyone can read todos"
  on public.todos
  for select              -- '읽기(select)' 동작에만 적용
  to anon, authenticated  -- 비로그인 손님(anon) + 로그인 사용자 모두
  using (true);           -- 어떤 줄을 보여줄지 조건. true = 전부 공개

-- (쓰기 정책) 누구나 할 일을 추가할 수 있게 허용 ------------------------
drop policy if exists "anyone can insert todos" on public.todos;
create policy "anyone can insert todos"
  on public.todos
  for insert              -- '쓰기(insert)' 동작에만 적용
  to anon, authenticated
  with check (true);      -- 새로 들어오는 줄을 검사하는 조건. true = 전부 허용


-- =====================================================================
-- (참고) 완료 토글(update)·삭제(delete)는 일부러 정책을 안 만들었습니다.
--   이번 실습의 deliverable은 'insert로 추가 + select로 목록'까지입니다.
--   완료 상태 update 는 실습 121, 삭제 delete 는 실습 122에서 정책과 함께 추가합니다.
--   정책이 없는 동작은 자동으로 막히므로(기본 거절), 지금은 안전한 상태입니다.
-- =====================================================================


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--   - anon key (공개 키, sb_publishable_...) : script.js·브라우저·깃허브에 올려도
--     되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전합니다.
--     → 이번 실습 script.js에는 반드시 이 anon 키만 넣습니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS를 통째로 우회하는 마스터 키 ★.
--     절대! 브라우저·코드·깃허브에 올리면 안 됩니다(서버에서만 비밀로 사용).
-- =====================================================================
