-- =====================================================================
-- 실습 257 — 예약 취소 링크: 고객이 '취소 토큰'으로 본인 예약을 DELETE
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이번 실습이 하는 일:
--   예약마다 '아무도 못 알아맞히는 비밀 번호표(취소 토큰)'를 하나씩 붙입니다.
--   예약 확정 메일에 그 토큰이 들어간 취소 링크
--     예) cancel.html?token=아주-긴-무작위-문자열
--   를 넣어 보냅니다. 손님이 그 링크를 누르면, 화면(JS)이 그 토큰과 '딱 맞는
--   예약 한 줄'을 DELETE 합니다. 즉 로그인 없이도 '본인 예약만' 지우게 만드는
--   = "토큰 기반 식별 + 삭제(DELETE)" 패턴입니다.
--
-- 왜 id(1, 2, 3…) 대신 토큰을 쓰나요?
--   id는 1, 2, 3 처럼 '맞히기 쉬운 번호'라, 1번부터 차례로 넣어 보면
--   남의 예약도 지울 수 있습니다(= 순번 추측 공격). 그래서 식별에는
--   '추측 불가능한 무작위 토큰(UUID)'을 씁니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0단계) 무작위 토큰을 자동 생성하기 위한 확장 켜기 (한 번만)
-- ---------------------------------------------------------------------
-- gen_random_uuid() 로 '추측 불가능한 긴 무작위 값'을 만들기 위해 켭니다.
create extension if not exists pgcrypto;


-- ---------------------------------------------------------------------
-- 1단계) 예약 표 만들기 (+ 취소 토큰 칸)
-- ---------------------------------------------------------------------
-- 실습 255의 reservations 표를 이어서 쓴다고 생각하세요.
-- 여기서는 '취소 토큰(cancel_token)' 칸이 핵심으로 추가됩니다.
create table if not exists public.reservations (
  id            bigint generated always as identity primary key,
  name          text        not null,           -- 예약자 이름
  slot_date     date        not null,           -- 예약 날짜 (예: 2026-06-20)
  slot_time     text        not null,           -- 예약 시간대 (예: '10:00')
  -- ★ 취소의 핵심: 줄마다 추측 불가능한 비밀 토큰을 자동 부여 ★
  cancel_token  uuid        not null default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  constraint reservations_slot_unique unique (slot_date, slot_time)
);

-- (이미 255에서 표를 만들었다면) 토큰 칸이 없을 수 있으니 안전하게 추가합니다.
alter table public.reservations
  add column if not exists cancel_token uuid not null default gen_random_uuid();


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻.
-- 켜는 순간 기본은 '전부 거절' → 아래에서 허락한 동작만 가능해집니다.
alter table public.reservations enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [삭제 정책] anon(공개)에게 DELETE를 허용 — 단, '토큰으로만' 지우게
-- ---------------------------------------------------------------------
-- 이번 실습의 진짜 핵심입니다. 두 가지가 함께 지켜져야 안전합니다.
--   (가) DELETE 자체는 허용한다 (취소 기능이 동작해야 하니까).
--   (나) 손님은 화면(JS)에서 반드시 .eq("cancel_token", 토큰) 으로
--        '딱 한 줄'만 지정해 지웁니다.
-- 그런데 '정책'만으로는 "토큰으로만 지정해라"를 강제하지 못합니다.
-- 그래서 아래 4단계에서 'cancel_token 칸을 못 읽게(SELECT 차단)' 막아,
-- 토큰을 모르는 사람은 애초에 어떤 줄을 지울지 특정할 수 없게 만듭니다.
drop policy if exists "cancel by token" on public.reservations;

create policy "cancel by token"
  on public.reservations
  for delete
  to anon, authenticated
  using (true);
-- using (true) 는 "삭제 동작 자체는 막지 않는다"는 뜻입니다.
-- 그럼 아무 줄이나 지워지지 않나요? → 핵심은 '무엇을 지울지 특정할 수 있느냐'입니다.
--   - 토큰을 아는 사람: 자기 토큰과 같은 '그 한 줄'만 .eq 로 지정해 지울 수 있음(정상 취소).
--   - 토큰을 모르는 사람: 어떤 줄을 지울지 특정할 단서(토큰)를 못 읽음(4단계 차단).
--     id(1,2,3…)로 찍어 지우는 추측 공격을 줄이려면, 화면/안내 어디에도 id를 노출하지 않습니다.
-- ※ "추측 공격까지 100% 막고 싶다" 면, 삭제는 브라우저가 아니라 서버에서
--    service_role 키로 처리하세요(README의 '더 단단히' 참고). 이번 실습은
--    'anon + 토큰'으로 취소 흐름의 원리를 익히는 한 단계짜리 미니 결과물입니다.


-- ---------------------------------------------------------------------
-- 4단계) [읽기 정책] 손님이 '내 예약 한 줄'을 토큰으로 확인은 하되,
--         토큰 칸 자체는 못 읽게(목록 캐기 방지)
-- ---------------------------------------------------------------------
-- 취소 페이지는 지우기 전에 "정말 이 예약 맞나요?" 확인 화면을 보여줘야 하므로
-- 읽기(SELECT)도 허용합니다. 다만 cancel_token 칸까지 누구나 읽을 수 있으면
-- 모든 사람의 토큰을 긁어가 남의 예약을 지울 수 있으니, '토큰 칸만' 막습니다.
drop policy if exists "read for confirm" on public.reservations;

create policy "read for confirm"
  on public.reservations
  for select
  to anon, authenticated
  using (true);

-- ★ 칼럼(열) 단위 차단 ★ : anon/authenticated 역할에서 cancel_token 열의 읽기 권한을 회수.
-- 이러면 손님이 select 해도 cancel_token 값은 결과에 나오지 않습니다(목록 캐기 차단).
-- (지우는 동작 자체는 .eq("cancel_token", 내가-아는-토큰) 으로 여전히 가능합니다.)
revoke select (cancel_token) on public.reservations from anon;
revoke select (cancel_token) on public.reservations from authenticated;


-- ---------------------------------------------------------------------
-- 5단계) (선택) 동작 확인용 — 토큰이 정해진 샘플 예약 한 줄 넣기
-- ---------------------------------------------------------------------
-- 아래를 실행하면 2026-06-20 10:00 예약이 '딱 정해진 토큰'으로 들어갑니다.
-- 그 토큰을 cancel.html?token=... 에 붙여 취소를 테스트할 수 있습니다.
-- (실서비스에서는 토큰을 직접 적지 말고 gen_random_uuid() 기본값에 맡기세요.
--  여기서는 테스트가 쉽도록 일부러 외우기 쉬운 값을 넣습니다.)
insert into public.reservations (name, slot_date, slot_time, cancel_token)
values (
  '샘플 예약자',
  '2026-06-20',
  '10:00',
  '00000000-0000-4000-8000-000000000257'   -- 테스트 전용 고정 토큰(자리표시자)
)
on conflict (slot_date, slot_time) do nothing;  -- 이미 있으면 조용히 넘어감

-- 위 샘플로 취소를 테스트하려면 cancel.html 을 이렇게 여세요:
--   cancel.html?token=00000000-0000-4000-8000-000000000257


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--
--   - anon key (공개 키, sb_publishable_...) : 브라우저·script·깃허브에 올려도
--     되는 '출입증'. RLS 정책의 통제를 그대로 받습니다. 이번 실습에선
--     'SELECT(토큰 칸 제외) + DELETE'만 허락했고, 무엇을 지울지는
--     '추측 불가능한 토큰'을 아는 사람만 특정할 수 있습니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     절대! 브라우저·코드·깃허브에 올리면 안 되고, 오직 서버(n8n·백엔드)에서만
--     비밀로 보관해 씁니다. "토큰 검증을 서버가 직접 한다"처럼 더 단단한 취소를
--     만들 땐 이 키를 서버에서만 사용하세요.
-- =====================================================================
