// 아래 두 값을 내 Supabase 프로젝트 값으로 바꾸세요. (대시보드 → Settings → API)
//
//  ┌─ anon(publishable) 키: '공개돼도 되는 출입증' ─────────────────┐
//  │ 브라우저·GitHub에 노출돼도 괜찮은 키입니다. 여기에 넣습니다.   │
//  └────────────────────────────────────────────────────────────┘
//  ┌─ service_role(secret) 키: '절대 숨겨야 하는 마스터키' ─────────┐
//  │ 모든 보안(RLS)을 통째로 우회합니다. 브라우저 코드(여기)에는    │
//  │ 절대 넣지 마세요! 서버(n8n·엣지 함수)에서 환경변수로만 씁니다. │
//  └────────────────────────────────────────────────────────────┘
//
// 아래 https://여기에-..., sb_publishable_... 는 '자리표시자'입니다. 내 값으로 바꾸세요.
const SUPABASE_URL = "https://여기에-내-프로젝트.supabase.co";
const SUPABASE_ANON_KEY = "sb_publishable_여기에-내-anon-키";

// Supabase 클라이언트 생성.
// persistSession 기본값이 true라, 한 번 로그인하면 새로고침해도 로그인 상태가 유지됩니다.
// (이 덕분에 가드가 새로고침 때마다 '로그인된 사람'으로 인식할 수 있습니다.)
const db = supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
