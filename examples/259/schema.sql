-- =====================================================================
-- 실습 259 — 게시판 표(posts) 만들기 + 보안(RLS) 설정
--            "로그인한 사람만 글쓰기" 를 DB가 강제하도록
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이번 실습이 하는 일:
--   - 글은 '누구나 읽을 수 있게'(공개 게시판) 합니다.            → SELECT 허용(전체)
--   - 글쓰기는 '로그인한 사람만' 할 수 있게 합니다.              → INSERT 허용(로그인만)
--   - 게다가 "내 글에는 내 이름표(user_id)만" 붙게 강제합니다.   → 본인 위조 방지
--   - 글 삭제는 '내가 쓴 글만' 지울 수 있게 합니다.             → DELETE 본인만
--
-- ★ 핵심 한 줄: 화면에서 글쓰기 버튼을 숨기는 건 '장식'일 뿐입니다.
--   진짜 잠금은 여기 RLS 정책에서 걸립니다. (로그인 안 한 사람이 코드로
--   직접 insert 를 시도해도 DB가 거절합니다.)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 게시판 표 만들기
-- ---------------------------------------------------------------------
-- user_id : '이 글의 글쓴이'를 가리킵니다.
--   - auth.users(로그인한 사용자 목록)의 id 를 참조합니다.
--   - default auth.uid() 덕분에, insert 할 때 user_id 를 직접 안 넣어도
--     Supabase 가 '지금 로그인한 사람의 id'를 자동으로 채워 줍니다.
create table if not exists public.posts (
  id          bigint generated always as identity primary key,
  user_id     uuid        not null default auth.uid()
                          references auth.users (id) on delete cascade, -- 글쓴이
  author      text,                                  -- 화면 표시용 글쓴이 이메일(편의용)
  content     text        not null,                  -- 글 내용
  created_at  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.posts enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [읽기 정책] 글은 누구나 SELECT 할 수 있게 허용 (공개 게시판)
-- ---------------------------------------------------------------------
-- to anon, authenticated : 비로그인 손님 + 로그인 사용자 모두 읽기 가능.
-- using (true)           : 모든 글 줄을 읽을 수 있다.
drop policy if exists "글은 누구나 읽기" on public.posts;
create policy "글은 누구나 읽기"
  on public.posts
  for select
  to anon, authenticated
  using (true);


-- ---------------------------------------------------------------------
-- 4단계) [쓰기 정책] 글쓰기는 '로그인한 사람'만 (← 이번 실습의 주인공)
-- ---------------------------------------------------------------------
-- to authenticated         : '로그인한 사용자'에게만 이 정책이 적용됩니다.
--                            (anon=비로그인 은 통과할 INSERT 정책이 없어 막힘)
-- with check (auth.uid() = user_id) :
--   새로 들어오는 글의 user_id 가 '지금 로그인한 나'와 같을 때만 허용.
--   → 남의 user_id 를 적어 글쓴이를 위조하려 하면 이 검사에서 막힙니다.
drop policy if exists "로그인한 사람만 글쓰기" on public.posts;
create policy "로그인한 사람만 글쓰기"
  on public.posts
  for insert
  to authenticated
  with check (auth.uid() = user_id);


-- ---------------------------------------------------------------------
-- 5단계) [삭제 정책] 내가 쓴 글만 지울 수 있게 허용
-- ---------------------------------------------------------------------
-- using (auth.uid() = user_id) : '그 글의 주인이 나일 때만' 삭제 가능.
--   → 남의 글은 코드로 delete 를 시도해도 DB가 거절합니다.
drop policy if exists "내 글만 삭제" on public.posts;
create policy "내 글만 삭제"
  on public.posts
  for delete
  to authenticated
  using (auth.uid() = user_id);


-- =====================================================================
-- (중요) 수정(UPDATE) 정책은 이번 실습에서 일부러 만들지 않았습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → 글 수정 기능이 필요하면 141번 실습의 update 정책을 참고해 추가하세요.
