-- =====================================================================
-- 실습 247 — 뉴스레터 구독자 표(subscribers) 만들기 + 보안(RLS) 설정
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이 실습의 보안 포인트:
--   브라우저(누구나 볼 수 있는 곳)에 anon(공개) 키가 박혀 있어도 안전하려면,
--   표에 RLS를 켜고 "구독 폼이 필요한 동작(INSERT)만" 정책으로 허락해야 합니다.
--   읽기(SELECT)는 일부러 안 열어 둡니다 → 남의 이메일 목록이 브라우저로
--   새어 나가지 않게 하기 위함입니다. (이메일은 개인정보!)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 구독자 표 만들기
-- ---------------------------------------------------------------------
-- email 에 unique 를 걸어 '같은 이메일 중복 구독'을 DB가 알아서 막아 줍니다.
create table if not exists public.subscribers (
  id          bigint generated always as identity primary key,
  email       text        not null unique,   -- 중복 구독 방지
  created_at  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.subscribers enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [쓰기 정책] 누구나 구독(INSERT)은 할 수 있게 허용
-- ---------------------------------------------------------------------
-- 정책을 다시 실행해도 에러 안 나게, 같은 이름이 있으면 먼저 지웁니다.
drop policy if exists "anyone can subscribe" on public.subscribers;

-- for insert         : 이 정책은 '쓰기(insert)' 동작에만 적용된다.
-- to anon, authenticated : 비로그인 손님(anon) + 로그인 사용자 모두 대상.
-- with check (true)  : '들어오려는 새 줄'을 검사하는 조건. true = 어떤 이메일이든 허용.
--                      (insert/update 에서는 using 대신 with check 를 씁니다.)
create policy "anyone can subscribe"
  on public.subscribers
  for insert
  to anon, authenticated
  with check (true);


-- =====================================================================
-- (중요) 읽기(SELECT) 정책은 일부러 만들지 않았습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → anon 키로는 구독자 이메일 '목록을 읽을 수 없습니다'.
--   → 구독은 되지만, 남의 이메일을 훔쳐볼 수는 없는 안전한 상태.
--
--   구독자 목록은 누가 보나요?
--     - 운영자(나)는 Supabase 대시보드 > Table editor 에서 직접 봅니다.
--       (대시보드는 service_role 권한으로 동작 → RLS와 무관하게 다 보임)
--     - 코드에서 목록을 읽어야 한다면, 그건 브라우저가 아니라
--       '서버(예: n8n, 백엔드)'에서 service_role 키로 해야 합니다.
-- =====================================================================


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--
--   - anon key (공개 키, sb_publishable_...) : 화면(브라우저)·script.js·깃허브에
--     올려도 되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전.
--     이번 실습에선 'INSERT만' 허락받았으므로, 구독은 되고 목록 읽기는 막힙니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     정책이 뭐든 무시하고 다 됩니다. 그래서 절대! 브라우저·코드·깃허브에 올리면 안 되고
--     오직 서버(예: n8n, 백엔드)에서만 비밀로 보관해 씁니다.
-- =====================================================================
