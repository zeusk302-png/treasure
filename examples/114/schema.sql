-- 이미 같은 이름의 표가 있으면 지우고 새로 만듭니다.
-- (연습용이라 안전하게 다시 만들 수 있게 넣어 둔 줄입니다.
--  실제 데이터가 든 표에는 함부로 쓰지 마세요.)
drop table if exists public.memos;

-- memos 표 만들기 -------------------------------------------------------
-- 컬럼(=표의 세로 칸) 3개:
--   id         : 글 한 줄마다 자동으로 붙는 고유 번호 (절대 안 겹침)
--   content    : 메모 내용(글자). 빈 값은 못 들어가게 막음
--   created_at : 이 줄이 만들어진 시각. 자동으로 '지금'이 채워짐
create table public.memos (
  id          bigint generated always as identity primary key,
  content     text        not null,
  created_at  timestamptz not null default now()
);

-- 컬럼에 설명 달기(선택) -------------------------------------------------
-- 나중에 표만 봐도 "이 칸이 뭐였더라?"를 알 수 있게 메모를 남깁니다.
comment on table  public.memos             is '실습 114: 한 줄 메모 저장용 첫 테이블';
comment on column public.memos.id          is '메모 고유 번호(자동 증가, 기본키)';
comment on column public.memos.content     is '메모 내용(필수, 빈 값 불가)';
comment on column public.memos.created_at  is '메모가 만들어진 시각(자동 기록)';

