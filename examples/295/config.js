//   (1) Supabase 연결값(URL + anon 공개 키)  ← 자리표시자를 내 값으로 바꾸세요.
//   (2) "지금까지 서버를 몇 번 두드렸나"를 세는 측정기(setupCounter)
//
// 핵심: N+1 문제는 "코드가 작동하느냐"가 아니라 "서버를 몇 번 두드리느냐"의 문제라,
//       반드시 '요청 횟수'를 눈으로 봐야 합니다. 그래서 측정기를 직접 만듭니다.

// -------------------------------------------------------------
// 1) 내 프로젝트 값 (Supabase 대시보드: Settings → API 에서 복사)
// -------------------------------------------------------------
//
// ▶ URL : 내 데이터베이스가 사는 인터넷 주소. 비밀이 아닙니다.
// ▶ anon 키(공개 키) : 브라우저에 그대로 박아도 되는 '출입증'입니다.
//    공개돼도 안전한 진짜 이유는 서버에 RLS(행 수준 보안)가 켜져 있기 때문입니다.
//    반대로 service_role 키(= sb_secret_... )는 모든 보안을 우회하는 '마스터 키'라
//    절대 브라우저나 깃허브에 올리면 안 됩니다.
//
// 아래 두 값은 '자리표시자'입니다. 내 진짜 값으로 바꿔 주세요.
const SUPABASE_URL = "https://여기에-내-프로젝트-ID.supabase.co";
const SUPABASE_ANON_KEY = "sb_publishable_여기에-내-anon-공개키-붙여넣기";

// -------------------------------------------------------------
// 2) 연결(클라이언트) 만들기
// -------------------------------------------------------------
const db = supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);

// 자리표시자를 안 바꿨으면 실수하기 쉬우니 먼저 친절하게 알려 줍니다.
function 설정이비었나() {
  return (
    SUPABASE_URL.includes("여기에-내") || SUPABASE_ANON_KEY.includes("여기에-내")
  );
}

// -------------------------------------------------------------
// 3) 요청 횟수 측정기
// -------------------------------------------------------------
//
// 브라우저가 서버로 보내는 모든 통신은 결국 fetch()를 거칩니다.
// 그래서 fetch를 '한 겹 감싸서(wrapping)' Supabase 주소(/rest/v1/)로 가는
// 요청만 1씩 셈하면, 실제 DB를 몇 번 두드렸는지 정확히 알 수 있습니다.
//
// 사용법:
//   const 측정 = setupCounter();   // 세기 시작 (0으로 초기화)
//   ... 여기서 DB 조회 ...
//   측정.멈추기();                 // 원래 fetch로 되돌리기
//   측정.횟수                      // 이 사이에 보낸 DB 요청 수
function setupCounter() {
  const 원래fetch = window.fetch;
  let count = 0;

  window.fetch = function (...args) {
    const url = String(args[0]);
    // Supabase REST 요청만 셈합니다. (실시간/인증 등 다른 통신은 제외)
    if (url.includes("/rest/v1/")) {
      count++;
      console.log("  → DB 요청 #" + count + ":", url.split("?")[0]);
    }
    return 원래fetch.apply(this, args);
  };

  return {
    get 횟수() {
      return count;
    },
    멈추기() {
      window.fetch = 원래fetch; // 측정이 끝나면 반드시 원상복구
    },
  };
}
