-- =====================================================================
-- 실습 119 — RLS(행 수준 보안) 켜기 + 읽기/쓰기 정책 추가하기
-- =====================================================================
-- 이 실습은 실습 116~118과 '같은 표(guestbook)'를 씁니다.
-- 116/117/118에서 이미 표를 만들었다면 표는 다시 만들 필요가 없습니다.
--
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- ★ 이 파일을 실행하기 전과 후의 차이를 꼭 눈으로 확인하세요.
--   - 실행 '전' (118까지): RLS가 꺼져 있어 anon 키로도 읽기·쓰기가 그냥 됩니다.
--   - 1단계만 실행 후 : RLS가 켜졌지만 정책이 0개 → 읽기는 빈 목록 [], 쓰기는 에러로 막힘.
--   - 2~3단계까지 실행 후 : 정책이 생겨서 다시 정상 동작. 이것이 '진짜 안전한' 상태입니다.
-- =====================================================================


-- (표가 아직 없다면 먼저 만들기) -------------------------------------
-- 116~118에서 이미 만들었다면 if not exists 라서 그냥 넘어갑니다.
create table if not exists public.guestbook (
  id          bigint generated always as identity primary key,
  name        text        not null,
  message     text        not null,
  created_at  timestamptz not null default now()
);


-- =====================================================================
-- 1단계) RLS(행 수준 보안) 켜기
-- =====================================================================
-- RLS = Row Level Security. "표의 줄(row) 하나하나마다 출입 통제를 건다"는 뜻입니다.
-- 이걸 켜는 순간, '정책(policy)으로 명시적으로 허락한 동작'만 가능해집니다.
--   허락(정책)이 하나도 없으면 → 기본은 '전부 거절'.
--   → 읽기(select)는 에러 대신 '빈 배열 []'을 돌려주고(아무 줄도 못 봄),
--     쓰기(insert)는 'new row violates row-level security policy' 에러로 막힙니다.
--
-- ▶ 여기까지만 실행하고 방명록을 새로고침해 보세요.
--   글이 분명히 있는데도 목록이 '텅 비어' 보이고, 글을 남기려 하면 에러가 납니다.
--   이게 바로 "정책이 없으면 데이터가 안 보이는" 보안의 기본입니다.
alter table public.guestbook enable row level security;


-- =====================================================================
-- 2단계) [읽기 정책] 누구나 글 목록을 볼 수 있게 허용
-- =====================================================================
-- 정책을 다시 실행해도 에러 안 나게, 같은 이름이 있으면 먼저 지웁니다.
drop policy if exists "anyone can read guestbook" on public.guestbook;

-- for select        : 이 정책은 '읽기(select)' 동작에만 적용된다.
-- to anon, authenticated : 로그인 안 한 손님(anon) + 로그인한 사용자 모두 대상.
-- using (true)      : '어떤 줄을 보여줄까'의 조건. true = 모든 줄을 허용(=전체 공개 읽기).
create policy "anyone can read guestbook"
  on public.guestbook
  for select
  to anon, authenticated
  using (true);


-- =====================================================================
-- 3단계) [쓰기 정책] 누구나 글을 남길 수 있게 허용
-- =====================================================================
drop policy if exists "anyone can insert guestbook" on public.guestbook;

-- for insert            : 이 정책은 '쓰기(insert)' 동작에만 적용된다.
-- with check (true)     : '들어오려는 새 줄이 정책을 통과하는가'의 조건.
--                         insert/update 에서는 using 대신 with check 를 씁니다.
--                         true = 어떤 새 글이든 다 허용(=전체 공개 쓰기).
create policy "anyone can insert guestbook"
  on public.guestbook
  for insert
  to anon, authenticated
  with check (true);


-- =====================================================================
-- (참고) 수정/삭제는 일부러 정책을 '안' 만들었습니다.
--   정책이 없으면 그 동작은 자동으로 막힙니다(기본 거절).
--   즉 지금 이 방명록은 "누구나 읽고, 누구나 새 글 쓰기는 되지만,
--   남의 글을 수정·삭제는 아무도 못 하는" 안전한 상태입니다.
--   (로그인 기반으로 '내 글만 수정/삭제'를 허용하는 건 다음 단계 주제입니다.)
-- =====================================================================


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀) 다시 정리]
--
--   - anon key (공개 키, sb_publishable_...) : 화면(브라우저)·script.js·깃허브에
--     올려도 되는 '출입증'. 단, anon 이 RLS 정책의 통제를 '그대로 받기' 때문에
--     공개해도 안전합니다. (오늘 켠 정책이 anon 손님에게 적용됩니다.)
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     정책이 뭐든 무시하고 다 됩니다. 그래서 절대! 브라우저·코드·깃허브에 올리면 안 되고
--     오직 서버(예: n8n, 백엔드)에서만 비밀로 보관해 씁니다.
--
--   ▶ 결론: "RLS를 켜고 정책을 달았기 때문에" 비로소 anon 키를 공개해도 안전해집니다.
--     RLS는 anon 에 대한 자물쇠이고, service_role 은 그 자물쇠를 무시하는 별도 열쇠입니다.
-- =====================================================================
