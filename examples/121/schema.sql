-- =====================================================================
-- 실습 121 — 할 일 완료 상태를 update로 서버에 반영하기 (todos 표에 '수정' 권한 추가)
-- =====================================================================
-- 120번에서 만든 todos 표는 '추가(insert)'와 '목록 보기(select)'만 가능했습니다.
-- 이번 121번에서는 체크박스로 완료/미완료를 바꿀 수 있게 '수정(update)' 동작을 켭니다.
--
-- ★ 왜 SQL을 또 실행하나요? ★
--   RLS(행 수준 보안)는 '정책으로 허락한 동작만' 통과시킵니다(기본은 전부 거절).
--   120번에서는 select·insert 정책만 만들었기 때문에, update는 자동으로 막혀 있습니다.
--   그래서 이번에 'update 정책'을 하나 더 추가해야 체크박스 토글이 서버에 저장됩니다.
--
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--   (120번을 이미 실행했다면, 1·2단계는 '이미 있으면 건너뛰기'라 안전합니다.
--    여러 번 실행해도 문제없게 만들어 뒀습니다.)
-- =====================================================================


-- =====================================================================
-- 1단계) todos 표 (120번에서 이미 만들었다면 그대로 둠)
-- =====================================================================
--   id          : 줄(row)을 구별하는 고유 번호. 서버가 1, 2, 3... 자동으로 매깁니다.
--                 → 이번 실습의 주인공! update할 때 "이 id의 줄만 바꿔라"라고 콕 집습니다.
--   text        : 할 일 내용
--   done        : 완료 여부. 기본값 false. → 이번 실습에서 true/false로 바꿀 컬럼입니다.
--   created_at  : 만든 시각. 서버가 자동으로 넣습니다.
create table if not exists public.todos (
  id          bigint generated always as identity primary key,
  text        text        not null,
  done        boolean     not null default false,
  created_at  timestamptz not null default now()
);


-- =====================================================================
-- 2단계) RLS(행 수준 보안) 켜기 (120번에서 이미 켰다면 그대로 둠)
-- =====================================================================
alter table public.todos enable row level security;


-- =====================================================================
-- 3단계) 읽기·쓰기 정책 (120번 것 그대로 유지) — 한 번 더 실행해도 안전
-- =====================================================================
-- (읽기) 누구나 목록을 볼 수 있게 허용
drop policy if exists "anyone can read todos" on public.todos;
create policy "anyone can read todos"
  on public.todos
  for select
  to anon, authenticated
  using (true);

-- (쓰기) 누구나 할 일을 추가할 수 있게 허용
drop policy if exists "anyone can insert todos" on public.todos;
create policy "anyone can insert todos"
  on public.todos
  for insert
  to anon, authenticated
  with check (true);


-- =====================================================================
-- ★ 4단계) 이번 실습의 핵심 — 누구나 할 일을 '수정(update)'할 수 있게 허용 ★
-- =====================================================================
-- 이 정책이 있어야 script.js의
--     db.from("todos").update({ done: true }).eq("id", id)
-- 가 막히지 않고 서버에 반영됩니다.
--
--   using       : '어떤 줄을 수정 대상으로 삼을지' 조건 (수정 전 줄을 본다)
--   with check  : '수정한 결과 줄이 통과해도 되는지' 조건 (수정 후 줄을 본다)
--   둘 다 true  = 모든 줄을, 어떤 값으로든 자유롭게 수정 허용
drop policy if exists "anyone can update todos" on public.todos;
create policy "anyone can update todos"
  on public.todos
  for update               -- '수정(update)' 동작에만 적용
  to anon, authenticated   -- 비로그인 손님(anon) + 로그인 사용자 모두
  using (true)             -- 수정할 줄을 고르는 조건. true = 전부 대상
  with check (true);       -- 수정된 줄을 검사하는 조건. true = 전부 허용


-- =====================================================================
-- (참고) 삭제(delete)는 일부러 아직 정책을 안 만들었습니다.
--   이번 실습의 deliverable은 'update로 완료 토글'까지입니다.
--   삭제 delete 는 실습 122에서 정책과 함께 추가합니다.
--   정책이 없는 동작은 자동으로 막히므로(기본 거절), 지금은 안전한 상태입니다.
-- =====================================================================


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--   - anon key (공개 키, sb_publishable_...) : script.js·브라우저·깃허브에 올려도
--     되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전합니다.
--     → 이번 실습 script.js에는 반드시 이 anon 키만 넣습니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS를 통째로 우회하는 마스터 키 ★.
--     절대! 브라우저·코드·깃허브에 올리면 안 됩니다(서버에서만 비밀로 사용).
--
--   ※ 이번 실습에서 'update를 누구나 허용'한 것은 학습용입니다. 실제 서비스라면
--     '로그인한 본인이 쓴 줄만 수정 가능'처럼 조건을 좁히는 것이 안전합니다(추후 학습).
-- =====================================================================
