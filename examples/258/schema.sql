-- =====================================================================
-- 실습 258 — 게시판 글 표(posts) 만들기 + 보안(RLS) 설정
-- =====================================================================
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
--
-- 이번 실습이 하는 일:
--   누구나 글을 '쓰고(INSERT/Create)' 올라온 글을 '읽는(SELECT/Read)'
--   가장 단순한 커뮤니티 게시판을 만듭니다. (CRUD 중 C·R 두 가지)
--   수정(Update)·삭제(Delete)는 일부러 빼서, anon(공개) 키로는
--   남의 글을 고치거나 지울 수 없게 합니다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1단계) 글 표 만들기
-- ---------------------------------------------------------------------
create table if not exists public.posts (
  id          bigint generated always as identity primary key,
  author      text        not null,            -- 글쓴이 이름
  content     text        not null,            -- 글 내용
  created_at  timestamptz not null default now()  -- 작성 시각(자동 기록)
);


-- ---------------------------------------------------------------------
-- 2단계) RLS(행 수준 보안) 켜기
-- ---------------------------------------------------------------------
-- RLS = Row Level Security. "표의 줄(row)마다 출입 통제를 건다"는 뜻입니다.
-- 켜는 순간 기본은 '전부 거절' → 아래 정책으로 허락한 동작만 가능해집니다.
alter table public.posts enable row level security;


-- ---------------------------------------------------------------------
-- 3단계) [읽기 정책] 누구나 글 목록을 SELECT(조회) 할 수 있게 허용
-- ---------------------------------------------------------------------
-- 게시판이니까 글은 누구나 볼 수 있어야 합니다.
drop policy if exists "anyone can read posts" on public.posts;

-- for select          : 이 정책은 '읽기(select)' 동작에만 적용된다.
-- to anon, authenticated : 비로그인 손님(anon) + 로그인 사용자 모두 대상.
-- using (true)        : 모든 글 줄을 읽을 수 있다.
create policy "anyone can read posts"
  on public.posts
  for select
  to anon, authenticated
  using (true);


-- ---------------------------------------------------------------------
-- 4단계) [쓰기 정책] 누구나 글을 INSERT(작성) 할 수 있게 허용
-- ---------------------------------------------------------------------
-- 이번 실습은 '로그인 없는 간단 게시판'이라, 누구나 글을 올릴 수 있게 합니다.
-- (로그인을 붙여 '로그인한 사람만 글쓰기'로 바꾸는 건 다음 실습에서 다룹니다.)
drop policy if exists "anyone can create post" on public.posts;

-- for insert          : '작성(insert)' 동작에만 적용.
-- with check (true)   : 들어오는 모든 새 글을 허용한다.
create policy "anyone can create post"
  on public.posts
  for insert
  to anon, authenticated
  with check (true);


-- =====================================================================
-- (중요) 수정(UPDATE)·삭제(DELETE) 정책은 일부러 만들지 않았습니다.
--   정책이 없는 동작은 자동으로 막힙니다(기본 거절).
--   → anon(공개) 키로는 글을 '고치거나 지울 수 없습니다'.
--   → 손님은 글을 '새로 쓰고, 목록을 읽기'만 할 수 있습니다.
--
--   글 수정/삭제는 누가 하나요?
--     - 운영자(나)는 Supabase 대시보드 > Table editor 에서 직접 지우거나 고칩니다.
--       (대시보드는 service_role 권한 → RLS와 무관하게 다 됩니다.)
--     - 코드로 수정/삭제 기능을 만들려면, 누가 쓴 글인지 가려내는 인증(로그인)과
--       '본인 글만 손댈 수 있는' 정책이 필요합니다. (다음 실습들에서 다룹니다.)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 5단계) (선택) 동작 확인용 — 샘플 글 두 개 미리 넣어 두기
-- ---------------------------------------------------------------------
-- 아래 두 줄을 실행하면, 페이지를 열자마자 목록에 글이 보입니다.
-- (원치 않으면 이 두 줄은 건너뛰어도 됩니다.)
insert into public.posts (author, content) values
  ('운영자', '게시판이 열렸어요. 자유롭게 글을 남겨 주세요!'),
  ('첫방문', '안녕하세요, 첫 글 남깁니다 :)');


-- =====================================================================
-- [보안 안내 — anon(공개) vs service_role(비밀)]
--
--   - anon key (공개 키, sb_publishable_...) : 화면(브라우저)·script.js·깃허브에
--     올려도 되는 '출입증'. RLS 정책의 통제를 그대로 받기 때문에 공개해도 안전.
--     이번 실습에선 'SELECT + INSERT'만 허락했으므로, 글 읽기/쓰기는 되고
--     남의 글 수정·삭제는 막힙니다.
--   - service_role key (비밀, sb_secret_...) : ★ RLS 자체를 통째로 우회하는 마스터 키 ★.
--     정책이 뭐든 무시하고 다 됩니다. 그래서 절대! 브라우저·코드·깃허브에 올리면 안 되고
--     오직 서버(예: n8n, 백엔드)에서만 비밀로 보관해 씁니다.
-- =====================================================================
