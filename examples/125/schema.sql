-- 실습 125 — 글이 많을 때 '페이지네이션'으로 10개씩 끊어 보기 (range + count)
-- =====================================================================
-- 이 실습은 실습 116~124에서 쓰던 것과 '같은 표(guestbook)'를 사용합니다.
-- 이미 표를 만들었다면 표 만드는 부분은 다시 실행할 필요가 없습니다.
--   (아래 create 문은 `if not exists` 라서 또 실행해도 안전합니다 — 이미 있으면 그냥 넘어감)
--
-- ★ 단, 페이지네이션은 '글이 많아야' 효과가 보입니다.
--   글이 5개뿐이면 한 페이지에 다 나와서 [다음] 버튼이 의미가 없어요.
--   그래서 이 파일은 연습용 글을 한 번에 25개 넣어 줍니다. (3페이지 분량)
--
-- 사용법:
--   Supabase 대시보드 왼쪽 메뉴 > SQL Editor > New query 에
--   아래 내용을 통째로 붙여넣고 오른쪽 위 [Run] 버튼을 누르세요.
-- =====================================================================

-- guestbook 표 만들기 --------------------------------------------------
-- 컬럼(=표의 세로 칸) 4개:
--   id         : 글 한 줄마다 자동으로 붙는 고유 번호 (절대 안 겹침, 기본키)
--   name       : 글쓴이 이름. 빈 값은 못 들어가게 막음
--   message    : 메시지 내용. 빈 값은 못 들어가게 막음
--   created_at : 이 줄이 만들어진 시각. 자동으로 '지금'이 채워짐
--                ★ 실습 125는 이 created_at 으로 '최신순 정렬'한 뒤,
--                  거기서 .range(시작, 끝) 으로 일부 구간만 잘라서 가져옵니다.
create table if not exists public.guestbook (
  id          bigint generated always as identity primary key,
  name        text        not null,
  message     text        not null,
  created_at  timestamptz not null default now()
);

-- 컬럼에 설명 달기(선택) -----------------------------------------------
comment on table  public.guestbook            is '방명록 글 저장 테이블 (실습 116~125 공용)';
comment on column public.guestbook.id         is '글 고유 번호(자동 증가, 기본키)';
comment on column public.guestbook.name       is '글쓴이 이름(필수)';
comment on column public.guestbook.message    is '메시지 내용(필수)';
comment on column public.guestbook.created_at is '글이 작성된 시각(자동 기록, 최신순 정렬 기준)';

-- 페이지네이션 확인용 연습 글 25개 한 번에 넣기 ------------------------
-- generate_series(1, 25) : 1부터 25까지 숫자를 차례로 만들어 주는 함수입니다.
--   그 숫자(g)를 이용해 '연습용 1번 글 ~ 25번 글'을 자동으로 만들어 넣습니다.
-- created_at 을 1분씩 차이 나게 넣어, 최신순 정렬이 뚜렷하게 보이도록 했습니다.
--   (g가 클수록 더 최근 시각 → 최신순으로 보면 '연습용 25번 글'이 맨 위)
-- ※ 이 블록을 두 번 실행하면 글이 50개가 됩니다(중복돼도 동작에는 문제 없음).
insert into public.guestbook (name, message, created_at)
select
  '연습' || g || '호',
  '페이지네이션 테스트용 글입니다. 일련번호 ' || g || '번.',
  now() - ((25 - g) || ' minutes')::interval
from generate_series(1, 25) as g;

-- =====================================================================
-- [핵심 개념] .range(from, to) 는 '몇 번째부터 몇 번째까지'를 잘라 오는 것
-- ---------------------------------------------------------------------
--   - range 는 0번부터 셉니다(0-based). 사람처럼 1번부터가 아닙니다!
--   - 한 페이지에 10개씩 보여 준다면:
--       1페이지 → .range(0, 9)    (0,1,2,...,9   = 10개)
--       2페이지 → .range(10, 19)  (10,11,...,19  = 10개)
--       3페이지 → .range(20, 24)  (20,21,...,24  = 남은 5개)
--     공식:  from = (페이지번호 - 1) * 10
--            to   = from + 10 - 1
--   - .select('*', { count: 'exact' }) 를 쓰면, 잘라 온 10개와 '함께'
--     표 전체 글이 총 몇 개인지(count)도 알려 줍니다.
--     → 이 총개수가 있어야 "전체 몇 페이지인지"를 계산할 수 있습니다.
--       총페이지수 = 올림(전체개수 / 10)
-- =====================================================================

