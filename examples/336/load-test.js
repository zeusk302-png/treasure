/*
  이 파일은 무엇인가:
  k6(부하테스트 도구)에게 "어떻게 부하를 줄지" 알려 주는 시나리오 스크립트입니다.
  `k6 run load-test.js` 로 실행합니다. (이 파일은 node가 아니라 k6가 실행합니다.)

  왜 있는가:
  내 서버가 "몇 명까지 버티나"를 숫자로 보려면, 가짜 손님 떼를 동시에 보내 보고
  초당 처리량(RPS)·응답시간(p95)·에러율을 측정해야 합니다. 이 파일이 그 떼를 어떻게
  보낼지(몇 명을, 몇 초 동안, 어디로) 정의합니다.

  핵심 개념(비전공자용 한 줄 설명):
  - VU(Virtual User, 가상 사용자): k6가 흉내 내는 '동시 손님 한 명'. VU가 많을수록 부하가 큼.
  - stages(단계): 손님 수를 천천히 늘렸다 줄이는 '리허설 시나리오'. 갑자기 0→100보다
    서서히 올려야 한계가 어디서 무너지는지 관찰하기 좋습니다.
  - p95: 응답시간을 빠른 순으로 줄 세웠을 때 95번째(상위 5% 느림) 값.
    평균은 빠른 사람들에 가려지지만, 진짜 불만은 이 '느린 5%'에서 나옵니다.

  안전 경고:
  BASE_URL은 반드시 "내 것"만 가리키게 두세요(기본값 localhost). 남의 서버를 넣고
  돌리면 공격으로 간주될 수 있습니다.
*/

import http from "k6/http"; // k6가 제공하는 HTTP 요청 모듈 (Node의 것이 아니라 k6 전용)
import { check, sleep } from "k6"; // check=응답 검증, sleep=손님이 잠깐 쉬는 시간 흉내

// 때릴 대상 주소. 환경변수 BASE_URL이 있으면 그걸 쓰고, 없으면 로컬 서버를 씁니다.
// 왜 환경변수로: 진짜 대상이 바뀌어도 코드를 안 고치고 `BASE_URL=... k6 run ...` 으로
// 넘길 수 있게 — 그리고 대상 주소를 코드에 '박지 않으려는' 습관을 들이기 위함입니다.
const BASE_URL = __ENV.BASE_URL || "http://localhost:3000";

// 어떤 길을 때릴지. 가벼운 길("/")과 무거운 길("/slow")을 바꿔 가며 비교해 보세요.
// 환경변수 TARGET_PATH로 바꿀 수 있습니다. 예: TARGET_PATH=/slow k6 run load-test.js
const TARGET_PATH = __ENV.TARGET_PATH || "/";

export const options = {
  // stages: 가상 사용자(VU)를 단계적으로 올렸다 내리는 리허설 시나리오.
  // 왜 이렇게: 처음 20명으로 가볍게, 그다음 50명으로 더 세게, 마지막에 0으로 식히며
  // "어느 인원수에서 응답시간이 튀는지"를 단계별로 관찰하기 위함입니다.
  // (한계를 찾고 싶으면 target 숫자를 100, 200으로 올려 가며 다시 실행하세요.)
  stages: [
    { duration: "20s", target: 20 }, // 0 → 20명으로 서서히 증가(워밍업)
    { duration: "20s", target: 50 }, // 20 → 50명으로 더 강하게
    { duration: "10s", target: 0 },  // 50 → 0명으로 식히기(쿨다운)
  ],

  // thresholds: '통과 기준'. 이 선을 넘으면 테스트가 FAIL로 끝납니다.
  // 왜 중요한가: CI(자동 검사)에 넣으면 "느려지거나 에러가 늘면 빌드를 빨갛게 만들어"
  // 자동으로 막아 줍니다. 사람이 매번 표를 안 봐도 합격/불합격이 갈립니다.
  thresholds: {
    http_req_duration: ["p(95)<500"], // 상위 5% 느린 응답도 500ms 안에 끝나야 합격
    http_req_failed: ["rate<0.01"],   // 실패율 1% 미만이어야 합격
  },
};

// VU(가상 사용자) 한 명이 반복해서 실행하는 동작. k6가 이 함수를 수없이 돌립니다.
export default function () {
  // 대상 주소로 GET 요청을 한 번 보냅니다.
  const res = http.get(`${BASE_URL}${TARGET_PATH}`);

  // 응답이 정상(200)인지 확인합니다. 통과/실패 비율이 요약표에 집계됩니다.
  // 왜: "요청은 갔는데 서버가 200이 아니라 500을 줬다" 같은 상황을 잡아내기 위함입니다.
  check(res, {
    "상태코드 200": (r) => r.status === 200,
  });

  // 손님이 요청 사이에 잠깐(0.5초) 쉬는 것을 흉내 냅니다.
  // 왜: 실제 사용자는 쉼 없이 새로고침을 누르지 않습니다. 약간의 쉼을 넣어야
  // 더 현실적인 부하 패턴이 됩니다. (이 값을 줄이면 더 공격적인 부하가 됩니다.)
  sleep(0.5);
}
